def resolve_niche(raw: str | None) -> str | None:
    """Map a free-text niche/service label to a canonical niche key, or None."""
    if not raw:
        return None
    key = str(raw).strip().lower()
    if not key:
        return None
    if key in NICHE_ALIASES:
        return NICHE_ALIASES[key]
    # Partial contains match (longest alias first to avoid short false positives)
    for alias, niche in sorted(NICHE_ALIASES.items(), key=lambda item: -len(item[0])):
        if alias in key:
            return niche
    # Exact canonical keys
    upper = key.upper().replace(" ", "_")
    if upper in NICHES:
        return upper
    return None
